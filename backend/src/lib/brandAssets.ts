/**
 * Brand image uploads (plans/wl-self-serve-brands.md §2.4 "Uploads", PR 13). Modelled on
 * lib/hackathon/media.ts.
 *
 *   1. upload-url: mint a signed upload token for `<seriesId>/tmp/<uuid>.<ext>` in the PRIVATE
 *      `brand-uploads` bucket (png/jpeg/webp, 10 MB; the bucket enforces both again).
 *   2. The browser uploads straight to storage.
 *   3. attach: download the tmp object, SNIFF it (PNG/JPEG/WebP only; SVG, GIF, AVIF refused),
 *      decode + RE-ENCODE with sharp (metadata stripped, animated input refused, pixel and size
 *      limits), write the fresh image to the PUBLIC `brand-assets` bucket at
 *      `<seriesId>/<slot>/<uuid>.<ext>` (upsert:false, immutable cache), delete the tmp object, then
 *      store the same-origin `/cdn/brand-assets/...` URL in the series row (audit row + config_version bump).
 *
 * Only server-generated bytes ever reach the public bucket. Both buckets are created by ops
 * (scripts/create-brand-asset-buckets.cjs); when they are missing every call fails closed with a 503.
 * Old asset objects are kept so history still resolves.
 */
import crypto from 'node:crypto';
import sharp from 'sharp';
import { createClient } from '@supabase/supabase-js';
import { Prisma } from '@prisma/client';
import { prisma } from '../config/database.js';
import { AppError } from '../middleware/error.js';
import { sanitizeFlyerArt } from './flyerArt.js';
export { sanitizeFlyerArt };
import { writeSeriesAudit, snapshotOf, type SeriesActorKind } from './seriesAudit.js';

export const UPLOAD_BUCKET = 'brand-uploads';
export const ASSET_BUCKET = 'brand-assets';
export const MAX_UPLOAD_BYTES = 10 * 1024 * 1024;
export const MAX_ASSET_BYTES = 5 * 1024 * 1024;
export const MAX_INPUT_PIXELS = 40e6;
export const CDN_PREFIX = '/cdn/brand-assets/';

export const UPLOAD_MIME: Record<string, string> = { 'image/png': 'png', 'image/jpeg': 'jpg', 'image/webp': 'webp' };

export const SLOTS = ['logo', 'logoLight', 'favicon', 'og', 'flyerPoster', 'flyerRollup'] as const;
export type AssetSlot = (typeof SLOTS)[number];

interface SlotSpec {
  /** Column on event_series, or the key inside flyer_art. */
  target: { column: 'logoUrl' | 'logoLightUrl' | 'faviconUrl' | 'ogImageUrl' } | { flyerKey: 'poster' | 'rollup' };
  width: number;
  height: number;
  /** `inside` keeps aspect (never enlarges); `cover` crops to exactly width x height. */
  fit: 'inside' | 'cover';
  maxBytes: number;
}

// Flyer sizes are the canvas sizes of POSTER_CONFIG / ROLLUP_CONFIG (1080x1440, 1080x2940).
export const SLOT_SPECS: Record<AssetSlot, SlotSpec> = {
  logo: { target: { column: 'logoUrl' }, width: 1024, height: 512, fit: 'inside', maxBytes: MAX_ASSET_BYTES },
  logoLight: { target: { column: 'logoLightUrl' }, width: 1024, height: 512, fit: 'inside', maxBytes: MAX_ASSET_BYTES },
  favicon: { target: { column: 'faviconUrl' }, width: 256, height: 256, fit: 'cover', maxBytes: MAX_ASSET_BYTES },
  og: { target: { column: 'ogImageUrl' }, width: 1200, height: 630, fit: 'cover', maxBytes: 1024 * 1024 },
  flyerPoster: { target: { flyerKey: 'poster' }, width: 1080, height: 1440, fit: 'cover', maxBytes: MAX_ASSET_BYTES },
  flyerRollup: { target: { flyerKey: 'rollup' }, width: 1080, height: 2940, fit: 'cover', maxBytes: MAX_ASSET_BYTES },
};

export const isSlot = (v: unknown): v is AssetSlot => typeof v === 'string' && (SLOTS as readonly string[]).includes(v);

// ---------- storage client (fails closed) ----------

const unavailable = () => new AppError('Image uploads are not available yet', 503, 'UPLOADS_UNAVAILABLE');

let _client: ReturnType<typeof createClient> | null = null;
export function setStorageClientForTest(c: unknown): void {
  _client = c as ReturnType<typeof createClient> | null;
}
function admin() {
  if (_client) return _client;
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) throw unavailable();
  _client = createClient(url, key);
  return _client;
}
const uploads = () => admin().storage.from(UPLOAD_BUCKET);
const assets = () => admin().storage.from(ASSET_BUCKET);
/** Supabase reports a missing bucket as an error saying so (status 404). */
const bucketMissing = (e: { message?: string } | null | undefined) => !!e && /bucket not found/i.test(e.message || '');

// ---------- paths ----------

const UUID = '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}';

/** True when `path` is a tmp upload for exactly this series. */
export function isTmpPathFor(path: unknown, seriesId: string): path is string {
  if (typeof path !== 'string' || path.length > 200) return false;
  const m = new RegExp(`^(${UUID})/tmp/${UUID}\\.(png|jpg|webp)$`).exec(path);
  return !!m && m[1] === seriesId;
}

export function validateUploadRequest(slot: unknown, mimeType: unknown, fileSize: unknown): { slot: AssetSlot; ext: string } {
  if (!isSlot(slot)) throw new AppError(`slot must be one of ${SLOTS.join(', ')}`, 400, 'VALIDATION_ERROR');
  if (typeof mimeType !== 'string' || !UPLOAD_MIME[mimeType]) {
    throw new AppError('Please upload a PNG, JPEG or WebP image (SVG, GIF and AVIF are not accepted)', 400, 'BAD_FILE_TYPE');
  }
  if (typeof fileSize !== 'number' || !Number.isFinite(fileSize) || fileSize <= 0) throw new AppError('Missing file size', 400, 'BAD_FILE_SIZE');
  if (fileSize > MAX_UPLOAD_BYTES) throw new AppError('That image is too big (10 MB max)', 413, 'FILE_TOO_BIG');
  return { slot, ext: UPLOAD_MIME[mimeType] };
}

export async function createAssetUploadUrl(seriesId: string, ext: string) {
  const path = `${seriesId}/tmp/${crypto.randomUUID()}.${ext}`;
  const { data, error } = await uploads().createSignedUploadUrl(path);
  if (bucketMissing(error)) throw unavailable();
  if (error || !data) throw new AppError('Could not start the upload. Please try again.', 502, 'UPLOAD_URL_FAILED');
  return { path, token: data.token };
}

// ---------- sniff + re-encode ----------

/** Magic-byte sniff. Returns 'image/png' | 'image/jpeg' | 'image/webp' or null (everything else, SVG/GIF/AVIF included). */
export function sniffBrandImage(buf: Buffer): string | null {
  if (buf.length < 12) return null;
  if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return 'image/jpeg';
  if (buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return 'image/png';
  if (buf.subarray(0, 4).toString('latin1') === 'RIFF' && buf.subarray(8, 12).toString('latin1') === 'WEBP') return 'image/webp';
  return null;
}

const badImage = (msg = 'That file does not look like a valid PNG, JPEG or WebP image') => new AppError(msg, 400, 'BAD_FILE_TYPE');

/** Decode, validate and re-encode to a fresh, metadata-free image for `slot`. Pure (no I/O). */
export async function processBrandImage(buf: Buffer, slot: AssetSlot): Promise<{ data: Buffer; contentType: 'image/png' | 'image/webp'; ext: 'png' | 'webp'; width: number; height: number }> {
  if (buf.length === 0 || buf.length > MAX_UPLOAD_BYTES) throw new AppError('That image is too big (10 MB max)', 413, 'FILE_TOO_BIG');
  if (!sniffBrandImage(buf)) throw badImage();
  const spec = SLOT_SPECS[slot];
  try {
    const meta = await sharp(buf, { limitInputPixels: MAX_INPUT_PIXELS, failOn: 'error' }).metadata();
    if ((meta.pages ?? 1) > 1) throw badImage('Animated images are not accepted');
    if (!meta.width || !meta.height) throw badImage();
    // sharp drops all metadata (EXIF/GPS/ICC) on output unless asked to keep it; rotate() applies orientation first.
    const pipeline = () =>
      sharp(buf, { limitInputPixels: MAX_INPUT_PIXELS, failOn: 'error' })
        .rotate()
        .resize({ width: spec.width, height: spec.height, fit: spec.fit, withoutEnlargement: spec.fit === 'inside' });
    let out = await pipeline().png({ compressionLevel: 9 }).toBuffer({ resolveWithObject: true });
    let ext: 'png' | 'webp' = 'png';
    if (out.data.length > spec.maxBytes) out = await pipeline().png({ compressionLevel: 9, palette: true, quality: 90 }).toBuffer({ resolveWithObject: true });
    if (out.data.length > spec.maxBytes && slot !== 'og') {
      out = await pipeline().webp({ quality: 88 }).toBuffer({ resolveWithObject: true });
      ext = 'webp';
    }
    if (out.data.length > spec.maxBytes) {
      throw new AppError('That image is too detailed to fit this slot\'s size limit. Try a simpler image.', 413, 'FILE_TOO_BIG');
    }
    return { data: out.data, contentType: ext === 'png' ? 'image/png' : 'image/webp', ext, width: out.info.width, height: out.info.height };
  } catch (e) {
    if (e instanceof AppError) throw e;
    throw badImage();
  }
}

// ---------- URL validation ----------

const URL_TAIL = '[A-Za-z0-9._/-]{1,160}';

/**
 * Asset URLs a brand may store: only `/cdn/brand-assets/<thisSeriesId>/...`, or (super-admin only)
 * the legacy `/brands/<slug>/...`. Never arbitrary https, so tracking pixels and remote swaps are blocked.
 */
export function isAllowedAssetUrl(url: unknown, seriesId: string, isSuperAdmin: boolean): url is string {
  if (typeof url !== 'string' || url.length > 300 || url.includes('..')) return false;
  if (new RegExp(`^${CDN_PREFIX}${seriesId}/${URL_TAIL}$`).test(url)) return true;
  return isSuperAdmin && new RegExp(`^/brands/${URL_TAIL}$`).test(url);
}

// ---------- attach / remove ----------

/** Persist `url` (or null = remove / use default) for one slot, with audit + config_version bump. */
async function writeSlot(opts: { seriesId: string; slot: AssetSlot; url: string | null; actorEmail: string; actorKind: SeriesActorKind; action: string }) {
  const { seriesId, slot, url } = opts;
  const spec = SLOT_SPECS[slot];
  return prisma.$transaction(async (tx) => {
    // Row lock: concurrent flyer slots (poster + rollup share flyer_art) serialize instead of losing an update.
    await tx.$queryRaw`SELECT id FROM event_series WHERE id = ${seriesId}::uuid FOR UPDATE`;
    const before = await tx.eventSeries.findFirst({ where: { id: seriesId } });
    if (!before) throw new AppError('Not found', 404, 'NOT_FOUND');
    const b = before as Record<string, any>;
    let data: Prisma.EventSeriesUpdateInput;
    let oldVal: unknown;
    let newVal: unknown;
    let field: string;
    if ('column' in spec.target) {
      field = spec.target.column;
      oldVal = b[field] ?? null;
      newVal = url;
      data = { [field]: url } as Prisma.EventSeriesUpdateInput;
    } else {
      field = 'flyerArt';
      const cur = { ...(sanitizeFlyerArt(b.flyerArt) ?? {}) } as Record<string, string>;
      oldVal = b.flyerArt ?? null;
      if (url) cur[spec.target.flyerKey] = url;
      else delete cur[spec.target.flyerKey];
      const next = Object.keys(cur).length ? cur : null;
      newVal = next;
      data = { flyerArt: next ?? Prisma.DbNull };
    }
    if (JSON.stringify(oldVal) === JSON.stringify(newVal)) return { slot, url, changed: false };
    await tx.eventSeries.update({ where: { id: seriesId }, data: { ...data, configVersion: { increment: 1 } } });
    await writeSeriesAudit(tx, {
      seriesId, actorEmail: opts.actorEmail, actorKind: opts.actorKind, action: opts.action,
      changes: { [field]: { old: oldVal, new: newVal } }, snapshot: snapshotOf(b),
    });
    return { slot, url, changed: true };
  });
}

export async function attachBrandAsset(opts: { seriesId: string; slot: AssetSlot; path: unknown; actorEmail: string; actorKind: SeriesActorKind }) {
  const { seriesId, slot, path } = opts;
  if (!isTmpPathFor(path, seriesId)) throw new AppError('Invalid upload path', 400, 'VALIDATION_ERROR');
  const { data: blob, error } = await uploads().download(path);
  if (bucketMissing(error)) throw unavailable();
  if (error || !blob) throw new AppError('We could not find your uploaded image. Please try again.', 400, 'FILE_MISSING');
  const discard = () => uploads().remove([path]).then(() => undefined, () => undefined);
  let processed;
  try {
    processed = await processBrandImage(Buffer.from(await blob.arrayBuffer()), slot);
  } catch (e) {
    await discard();
    throw e;
  }
  const finalPath = `${seriesId}/${slot}/${crypto.randomUUID()}.${processed.ext}`;
  const up = await assets().upload(finalPath, processed.data, { contentType: processed.contentType, upsert: false, cacheControl: '31536000' });
  if (bucketMissing(up.error)) throw unavailable();
  if (up.error) throw new AppError('Could not store your image. Please try again.', 502, 'STORE_FAILED');
  await discard();
  const url = `${CDN_PREFIX}${finalPath}`;
  if (!isAllowedAssetUrl(url, seriesId, false)) throw new AppError('Could not store your image. Please try again.', 502, 'STORE_FAILED');
  const result = await writeSlot({ seriesId, slot, url, actorEmail: opts.actorEmail, actorKind: opts.actorKind, action: 'asset.update' });
  return { ...result, width: processed.width, height: processed.height };
}

/** "Remove (use default)": clears the slot. The stored object is kept so history stays valid. */
export function removeBrandAsset(opts: { seriesId: string; slot: AssetSlot; actorEmail: string; actorKind: SeriesActorKind }) {
  return writeSlot({ ...opts, url: null, action: 'asset.remove' });
}

// ---------- cron: abandoned tmp uploads ----------

const TMP_MAX_AGE_MS = 24 * 3600_000;
const CLEANUP_MAX_DELETES = 1000;
const CLEANUP_MAX_LISTS = 2000;

type StoreLike = {
  list: (prefix: string, opts: { limit: number; offset?: number }) => Promise<{ data: Array<{ id: string | null; name: string; created_at?: string | null }> | null; error?: { message?: string } | null }>;
  remove: (paths: string[]) => Promise<unknown>;
};

/**
 * Daily cron: delete `<seriesId>/tmp/*` objects in `brand-uploads` older than 24h (attach deletes its tmp
 * object, so anything that old was abandoned). Touches ONLY `<uuid>/tmp/` paths. A missing bucket or
 * unconfigured storage is a no-op (`skipped`), never an error.
 */
export async function cleanupAbandonedBrandUploads(now: Date = new Date(), store?: StoreLike): Promise<{ scanned: number; deleted: number; skipped?: string }> {
  let s = store;
  if (!s) {
    if (!process.env.SUPABASE_URL || !process.env.SUPABASE_SERVICE_ROLE_KEY) return { scanned: 0, deleted: 0, skipped: 'storage not configured' };
    s = uploads() as unknown as StoreLike;
  }
  const cutoff = now.getTime() - TMP_MAX_AGE_MS;
  const uuidRe = new RegExp(`^${UUID}$`);
  const isFolder = (e: { id: string | null; name: string }) => !e.id && !!e.name;
  let lists = 0;
  let scanned = 0;
  const doomed: string[] = [];
  const list = async (prefix: string) => {
    lists++;
    const r = await s!.list(prefix, { limit: 1000 });
    if (bucketMissing(r.error)) throw unavailable();
    return r.data ?? [];
  };
  try {
    for (const dir of (await list('')).filter((e) => isFolder(e) && uuidRe.test(e.name))) {
      if (lists >= CLEANUP_MAX_LISTS || doomed.length >= CLEANUP_MAX_DELETES) break;
      const files = await list(`${dir.name}/tmp`);
      scanned += files.length;
      for (const f of files) {
        if (f.id && f.created_at && new Date(f.created_at).getTime() < cutoff) doomed.push(`${dir.name}/tmp/${f.name}`);
      }
    }
  } catch (e) {
    if (e instanceof AppError && e.code === 'UPLOADS_UNAVAILABLE') return { scanned: 0, deleted: 0, skipped: 'bucket missing' };
    throw e;
  }
  const batch = doomed.slice(0, CLEANUP_MAX_DELETES);
  if (batch.length) await s.remove(batch);
  return { scanned, deleted: batch.length };
}
