// Generates src/generated/openapi.ts from the JSDoc in src/routes/v1/*.ts.
// Run: npm run gen:openapi  (also runs as part of `npm run build`).
// The output is committed so the Vercel function bundle never needs runtime globs.
import swaggerJsdoc from 'swagger-jsdoc';
import { writeFileSync } from 'node:fs';
import { swaggerOptions } from '../src/swaggerOptions.js';

const spec = swaggerJsdoc(swaggerOptions);
const out = new URL('../src/generated/openapi.ts', import.meta.url);
writeFileSync(
  out,
  `// GENERATED by scripts/gen-openapi.ts - do not edit. Run \`npm run gen:openapi\`.\n` +
    `/* eslint-disable */\nexport const openapiSpec: any = ${JSON.stringify(spec, null, 2)};\n`
);
console.log(`wrote ${Object.keys((spec as any).paths ?? {}).length} paths`);
